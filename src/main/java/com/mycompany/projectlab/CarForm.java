    private void saveCarsToFile() {
    try {
        FileOutputStream fos = new FileOutputStream("cars.dat");
        ObjectOutputStream oos = new ObjectOutputStream(fos);

        oos.writeObject(carList);

        oos.close();
        fos.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
                "Error saving cars!",
                "File Error",
                JOptionPane.ERROR_MESSAGE);
    }
}
    private void loadCarsFromFile() {
    try {
        FileInputStream fis = new FileInputStream("cars.dat");
        ObjectInputStream ois = new ObjectInputStream(fis);

        carList = (ArrayList<Car>) ois.readObject();

        ois.close();
        fis.close();

    } catch (Exception e) {
        // File may not exist on first run – this is OK
    }
}




